using UnityEngine;
using UnityEngine.InputSystem;

[RequireComponent(typeof(Rigidbody))]
[RequireComponent(typeof(CapsuleCollider))]
public class Movement : MonoBehaviour
{
    private Rigidbody rb;
    private GAD213.Shotgun.WeaponSystem shotgunControls;
    private CapsuleCollider capsule;

    // MOVEMENT
   

    [Header("Movement")]

    [Tooltip("Normal walking speed")]
    [SerializeField] private float walkSpeed = 4f;

    [Tooltip("Running speed")]
    [SerializeField] private float runSpeed = 8f;

    [Tooltip("Movement speed while crouching")]
    [SerializeField] private float crouchSpeed = 2f;

    [Tooltip("How quickly the player reaches the target movement speed")]
    [SerializeField] private float acceleration = 20f;

    [Tooltip("How quickly the player slows down")]
    [SerializeField] private float deceleration = 25f;

    private bool previousRunningState = false;

    private Vector3 moveInput = Vector3.zero;
    private float targetMoveSpeed = 0f;

    public bool isRunning = false;
    public bool isCrouching = false;



    // STAMINA
    

    [Header("Stamina")]

    [Tooltip("Maximum stamina")]
    [SerializeField] private float maxStamina = 3f;

    [Tooltip("Current stamina")]
    [SerializeField] private float currentStamina = 3f;

    [Tooltip("How much stamina is used every second while running")]
    [SerializeField] private float staminaDrainRate = 2f;

    [Tooltip("How much stamina is recovered every second")]
    [SerializeField] private float staminaRecoveryRate = 1f;

    [Tooltip("Delay before stamina begins recovering")]
    [SerializeField] private float staminaRecoveryDelay = 2f;

    [Tooltip("Amount of stamina required before the player can run again after exhaustion")]
    [SerializeField] private float staminaRequiredAfterExhaustion = 3f;

    private float staminaRecoveryTimer = 0f;
    private bool exhausted = false;

    public float CurrentStamina => currentStamina;
    public float MaxStamina => maxStamina;
    public bool IsExhausted => exhausted;

    // CROUCH
    
    [Header("Crouching")]

    [SerializeField] private float crouchHeight = 1f;
    [SerializeField] private float standingHeight = 2f;

    [SerializeField] private float crouchCameraHeight = 0.6f;
    [SerializeField] private float standingCameraHeight = 1f;

    [Tooltip("How quickly the camera and collider change between standing and crouching")]
    [SerializeField] private float crouchTransitionSpeed = 8f;


    // NOISE


    [Header("Noise")]

    [Tooltip("How far enemies can hear normal walking")]
    [SerializeField] private float walkNoiseRadius = 4f;

    [Tooltip("How far enemies can hear running")]
    [SerializeField] private float runNoiseRadius = 8f;

    [Tooltip("Current gameplay noise radius generated by the player")]
    [SerializeField] private float currentNoiseRadius = 0f;

    public float CurrentNoiseRadius => currentNoiseRadius;


    // GROUND SENSOR
 
    [Header("Ground Sensor")]

    [Tooltip("Radius of the sphere used to detect the ground")]
    [SerializeField] private float groundSensorRadius = 0.2f;

    [Tooltip("Vertical offset of the ground sensor")]
    [SerializeField] private float groundSensorOffset = -0.9f;

    [Tooltip("Layers counted as ground")]
    [SerializeField] private LayerMask groundLayer;

    public bool onGround = false;


    // CAMERA / ROTATION
    

    [Header("Rotation")]

    [SerializeField] private float yaw = 0f;
    [SerializeField] private float pitch = 0f;

    [Tooltip("Horizontal mouse sensitivity")]
    [SerializeField] private float yawSpeed = 10f;

    [Tooltip("Vertical mouse sensitivity")]
    [SerializeField] private float pitchSpeed = 10f;

    public Transform childCamera;

    [SerializeField] private float pitchMinimum = -80f;
    [SerializeField] private float pitchMaximum = 80f;


  
    // START


    private void Start()
    {
        Cursor.lockState = CursorLockMode.Locked;
        Cursor.visible = false;

        shotgunControls = GetComponent<GAD213.Shotgun.WeaponSystem>();
        rb = GetComponent<Rigidbody>();
        capsule = GetComponent<CapsuleCollider>();

        rb.constraints = RigidbodyConstraints.FreezeRotation;

        currentStamina = maxStamina;

        capsule.height = standingHeight;

        capsule.center = new Vector3(
            capsule.center.x,
            standingHeight / 2f,
            capsule.center.z
        );
    }


   
    // UPDATE
    

    private void Update()
    {
        var health=GetComponent<GAD213.Shotgun.PlayerHealth>();
        if(Time.timeScale<=0 || (health && health.BlockGameplay))return;
        if (!shotgunControls || (!GAD213.Shotgun.PrototypeInput.MenuHeld && shotgunControls.Captured)) HandleMouseLook();

        HandleCrouch();

        HandleMovementInput();
        if (isRunning != previousRunningState)
{
    if (isRunning)
    {
        Debug.Log("RUNNING - Speed: " + runSpeed);
    }
    else
    {
        Debug.Log("WALKING - Speed: " + walkSpeed);
    }

    previousRunningState = isRunning;
}

        HandleStamina();

        UpdateNoise();

        UpdateCameraHeight();
    }


  
    // MOUSE LOOK
   

    private void HandleMouseLook()
    {
        if (Mouse.current == null)
            return;

        Vector2 mouseDelta = Mouse.current.delta.ReadValue();

        // Kept the original camera feel you preferred.
        yaw += mouseDelta.x * yawSpeed * Time.deltaTime;

        pitch = Mathf.Clamp(
            pitch - mouseDelta.y * pitchSpeed * Time.deltaTime,
            pitchMinimum,
            pitchMaximum
        );

        transform.rotation = Quaternion.Euler(
            0f,
            yaw,
            0f
        );

        if (childCamera != null)
        {
            childCamera.localRotation = Quaternion.Euler(
                pitch,
                0f,
                0f
            );
        }
    }


    // MOVEMENT INPUT


    private void HandleMovementInput()
    {
        if (Keyboard.current == null)
            return;

        float horizontal =
            (Keyboard.current.aKey.isPressed ? -1f : 0f) +
            (Keyboard.current.dKey.isPressed ? 1f : 0f);

        float vertical =
            (Keyboard.current.sKey.isPressed ? -1f : 0f) +
            (Keyboard.current.wKey.isPressed ? 1f : 0f);

        moveInput = new Vector3(
            horizontal,
            0f,
            vertical
        );

        // Prevents diagonal movement from being faster.
        if (moveInput.magnitude > 1f)
        {
            moveInput.Normalize();
        }

        bool isMoving =
            moveInput.sqrMagnitude > 0.01f;

        bool wantsToRun =
            Keyboard.current.leftShiftKey.isPressed &&
            isMoving &&
            !isCrouching &&
            !exhausted &&
            currentStamina > 0f;

        isRunning = wantsToRun;

        if (!isMoving)
        {
            targetMoveSpeed = 0f;
        }
        else if (isCrouching)
        {
            targetMoveSpeed = crouchSpeed;
        }
        else if (isRunning)
        {
            targetMoveSpeed = runSpeed;
        }
        else
        {
            targetMoveSpeed = walkSpeed;
        }
    }


  
    // STAMINA
   

    private void HandleStamina()
    {
        if (isRunning)
        {
            currentStamina -=
                staminaDrainRate * Time.deltaTime;

            staminaRecoveryTimer =
                staminaRecoveryDelay;

            if (currentStamina <= 0f)
            {
                currentStamina = 0f;

                if (!exhausted)
                {
                    Debug.Log("Player is out of stamina!");
                }

                exhausted = true;
                isRunning = false;

                // Player drops back to normal walking speed
                // after running out of stamina.
                if (moveInput.sqrMagnitude > 0.01f)
                {
                    targetMoveSpeed = walkSpeed;
                }
                else
                {
                    targetMoveSpeed = 0f;
                }
            }
        }
        else
        {
            if (staminaRecoveryTimer > 0f)
            {
                staminaRecoveryTimer -=
                    Time.deltaTime;
            }
            else
            {
                currentStamina +=
                    staminaRecoveryRate * Time.deltaTime;
            }
        }

        currentStamina = Mathf.Clamp(
            currentStamina,
            0f,
            maxStamina
        );

        if (
            exhausted &&
            currentStamina >= staminaRequiredAfterExhaustion
        )
        {
            exhausted = false;

            Debug.Log(
                "Player has recovered enough stamina to run again."
            );
        }
    }



    // CROUCH
  

    private void HandleCrouch()
    {
        if (Keyboard.current == null)
            return;

        isCrouching =
            Keyboard.current.leftCtrlKey.isPressed;

        float targetHeight =
            isCrouching
                ? crouchHeight
                : standingHeight;

        capsule.height = Mathf.Lerp(
            capsule.height,
            targetHeight,
            crouchTransitionSpeed * Time.deltaTime
        );

        Vector3 centre = capsule.center;

        centre.y =
            capsule.height / 2f;

        capsule.center = centre;
    }


   
    // CAMERA HEIGHT
  

    private void UpdateCameraHeight()
    {
        if (childCamera == null)
            return;

        float targetHeight =
            isCrouching
                ? crouchCameraHeight
                : standingCameraHeight;

        Vector3 cameraPosition =
            childCamera.localPosition;

        cameraPosition.y = Mathf.Lerp(
            cameraPosition.y,
            targetHeight,
            crouchTransitionSpeed * Time.deltaTime
        );

        childCamera.localPosition =
            cameraPosition;
    }


 
    // NOISE


    private void UpdateNoise()
    {
        if (rb == null)
            return;

        Vector3 horizontalVelocity =
            new Vector3(
                rb.linearVelocity.x,
                0f,
                rb.linearVelocity.z
            );

        bool moving =
            horizontalVelocity.sqrMagnitude > 0.01f;

        // Standing still makes no noise.
        if (!moving)
        {
            currentNoiseRadius = 0f;
            return;
        }

        // Crouching is completely silent.
        if (isCrouching)
        {
            currentNoiseRadius = 0f;
            return;
        }

        // Running is loud.
        if (isRunning)
        {
            currentNoiseRadius =
                runNoiseRadius;

            return;
        }

        // Normal walking.
        currentNoiseRadius =
            walkNoiseRadius;
    }



    // PHYSICS
  

    private void FixedUpdate()
    {
        CheckGround();

        Vector3 targetWorldVelocity =
            (
                transform.forward * moveInput.z +
                transform.right * moveInput.x
            ) * targetMoveSpeed;

        Vector3 currentHorizontalVelocity =
            new Vector3(
                rb.linearVelocity.x,
                0f,
                rb.linearVelocity.z
            );

        float changeRate;

        if (
            targetWorldVelocity.magnitude >
            currentHorizontalVelocity.magnitude
        )
        {
            changeRate = acceleration;
        }
        else
        {
            changeRate = deceleration;
        }

        Vector3 newHorizontalVelocity =
            Vector3.MoveTowards(
                currentHorizontalVelocity,
                targetWorldVelocity,
                changeRate * Time.fixedDeltaTime
            );

        rb.linearVelocity =
            new Vector3(
                newHorizontalVelocity.x,
                rb.linearVelocity.y,
                newHorizontalVelocity.z
            );
    }


   
    // GROUND DETECTION
  

    private void CheckGround()
    {
        Vector3 sensorPosition =
            transform.position +
            Vector3.up * groundSensorOffset;

        onGround = Physics.CheckSphere(
            sensorPosition,
            groundSensorRadius,
            groundLayer,
            QueryTriggerInteraction.Ignore
        );
    }


   
    // DEBUG
   

    private void OnDrawGizmosSelected()
    {
        // Ground sensor
        Gizmos.color = Color.red;

        Gizmos.DrawWireSphere(
            transform.position +
            Vector3.up * groundSensorOffset,
            groundSensorRadius
        );


        // Noise radius
        if (currentNoiseRadius > 0f)
        {
            Gizmos.color =
                isRunning
                    ? Color.yellow
                    : Color.cyan;

            Gizmos.DrawWireSphere(
                transform.position,
                currentNoiseRadius
            );
        }
    }
}